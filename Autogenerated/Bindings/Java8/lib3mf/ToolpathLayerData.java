	/**
	 * Adds a custom data DOM tree to the layer. Layer MUST not be finished when changing the DOM tree.
	 *
	 * @param nameSpace Namespace of the custom data tree. MUST not be empty.
	 * @param dataName Root name of the data tree. MUST not be empty. MUST be a valid XML name string.
	 * @return DOM Tree of the data.
	 * @throws Lib3MFException
	 */
	public CustomDOMTree addCustomData(String nameSpace, String dataName) throws Lib3MFException {
		byte[] bytesNameSpace = nameSpace.getBytes(StandardCharsets.UTF_8);
		Memory bufferNameSpace = new Memory(bytesNameSpace.length + 1);
		bufferNameSpace.write(0, bytesNameSpace, 0, bytesNameSpace.length);
		bufferNameSpace.setByte(bytesNameSpace.length, (byte)0);
		byte[] bytesDataName = dataName.getBytes(StandardCharsets.UTF_8);
		Memory bufferDataName = new Memory(bytesDataName.length + 1);
		bufferDataName.write(0, bytesDataName, 0, bytesDataName.length);
		bufferDataName.setByte(bytesDataName.length, (byte)0);
		Pointer bufferData = new Memory(8);
		mWrapper.checkError(this, mWrapper.lib3mf_toolpathlayerdata_addcustomdata.invokeInt(new java.lang.Object[]{mHandle, bufferNameSpace, bufferDataName, bufferData}));
		Pointer valueData = bufferData.getPointer(0);
		CustomDOMTree data = null;
		if (valueData == Pointer.NULL) {
		  throw new Lib3MFException(Lib3MFException.LIB3MF_ERROR_INVALIDPARAM, "Data was a null pointer");
		}
		data = mWrapper.PolymorphicFactory(valueData, CustomDOMTree.class);
		return data;
	}

