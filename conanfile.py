from conan import ConanFile
from conan.tools.cmake import CMake, CMakeDeps, CMakeToolchain, cmake_layout
from conan.tools.files import copy
import os


class Lib3mfConan(ConanFile):
    name = "lib3mf"
    version = "2.4.2"
    license = "BSD-2-Clause"
    url = "https://github.com/3MFConsortium/lib3mf"
    description = "Implementation of the 3D Manufacturing Format (3MF) file standard"
    topics = ("3mf", "3d-printing", "geometry", "cad")
    settings = "os", "compiler", "build_type", "arch"
    options = {
        "shared": [True, False],
        "fPIC": [True, False],
    }
    default_options = {
        "shared": True,
        "fPIC": True,
    }

    exports_sources = (
        "CMakeLists.txt",
        "cmake/*",
        "Include/*",
        "Source/*",
        "Autogenerated/*",
        "Libraries/*",
        "Tests/*",
        "lib3mf.pc.in",
        "Documentation/*",
        "SDK/*",
        "CI/*",
    )

    def layout(self):
        cmake_layout(self, src_folder=".")

    def configure(self):
        if self.options.shared:
            self.options.rm_safe("fPIC")

    def requirements(self):
        self.requires("zlib/1.3.1")
        self.requires("libzip/1.10.1")
        self.requires("fast_float/5.3.0")

    def generate(self):
        deps = CMakeDeps(self)
        deps.generate()

        toolchain = CMakeToolchain(self)
        toolchain.variables["BUILD_SHARED_LIBS"] = "ON" if self.options.shared else "OFF"
        if self.options.get_safe("fPIC") is not None:
            toolchain.variables["CMAKE_POSITION_INDEPENDENT_CODE"] = "ON" if self.options.fPIC else "OFF"
        toolchain.variables["USE_INCLUDED_ZLIB"] = "OFF"
        toolchain.variables["USE_INCLUDED_LIBZIP"] = "OFF"
        toolchain.variables["USE_INCLUDED_SSL"] = "OFF"
        toolchain.variables["LIB3MF_TESTS"] = "OFF"
        toolchain.generate()

    def build(self):
        cmake = CMake(self)
        cmake.configure()
        cmake.build()
        # Tests are not built in this package configuration.

    def package(self):
        cmake = CMake(self)
        cmake.install()
        copy(self, "LICENSE", self.source_folder, os.path.join(self.package_folder, "licenses"))

    def package_info(self):
        self.cpp_info.set_property("cmake_file_name", "lib3mf")
        self.cpp_info.set_property("cmake_target_name", "lib3mf::lib3mf")
        self.cpp_info.libs = ["3mf"]
        self.cpp_info.includedirs = [
            "include/lib3mf",
            "include/lib3mf/Bindings/Cpp",
        ]
        self.cpp_info.requires.append("zlib::zlib")
        self.cpp_info.requires.append("libzip::zip")
        self.cpp_info.requires.append("fast_float::fast_float")
