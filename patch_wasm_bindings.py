def apply_literal_patch(contents: str, old: str, new: str, description: str) -> tuple[str, bool]:
    if new in contents:
        return contents, False
    if old not in contents:
        raise RuntimeError(f"missing expected pattern for {description}")
    return contents.replace(old, new, 1), True


def main() -> int:
    target = Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_BINDING
    contents = target.read_text(encoding="utf-8")
    changed = False

    contents, local_changed = apply_literal_patch(
        contents,
        BOOLEAN_BROKEN,
        BOOLEAN_FIXED,
        "BooleanObject_GetOperand",
    )
    changed = changed or local_changed

    for old, new in VECTOR_STRUCT_PATCHES:
        contents, local_changed = apply_literal_patch(
            contents,
            old,
            new,
            old.split("{", 1)[0].strip(),
        )
        changed = changed or local_changed

    if changed:
        target.write_text(contents, encoding="utf-8")
        print(f"{target}: patched WASM bindings")
    else:
        print(f"{target}: already patched")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
